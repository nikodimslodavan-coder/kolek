inline uint32_t nextCodepoint(const std::string& s, size_t& i)
{
    unsigned char c = static_cast<unsigned char>(s[i]);
    if (c < 0x80) { ++i; return c; }
    if ((c >> 5) == 0x6 && i + 1 < s.size()) {
        uint32_t cp = ((c & 0x1F) << 6) | (static_cast<unsigned char>(s[i + 1]) & 0x3F);
        i += 2;
        return cp;
    }
    if ((c >> 4) == 0xE && i + 2 < s.size()) {
        uint32_t cp = ((c & 0x0F) << 12) |
                      ((static_cast<unsigned char>(s[i + 1]) & 0x3F) << 6) |
                      (static_cast<unsigned char>(s[i + 2]) & 0x3F);
        i += 3;
        return cp;
    }
    if ((c >> 3) == 0x1E && i + 3 < s.size()) {
        uint32_t cp = ((c & 0x07) << 18) |
                      ((static_cast<unsigned char>(s[i + 1]) & 0x3F) << 12) |
                      ((static_cast<unsigned char>(s[i + 2]) & 0x3F) << 6) |
                      (static_cast<unsigned char>(s[i + 3]) & 0x3F);
        i += 4;
        return cp;
    }
    ++i;
    return '?';
}

inline uint32_t normalize(uint32_t cp)
{
    if (cp >= 0x430 && cp <= 0x44F) return cp - 0x20; // строчные -> заглавные
    if (cp == 0x451) return 0x415;                    // ё -> Е
    if (cp == 0x401) return 0x415;                    // Ё -> Е
    if (cp == 0x2013 || cp == 0x2014) return 0x2D;    // тире -> дефис
    return cp;
}

inline int utf8Length(const std::string& s)
{
    int n = 0;
    for (unsigned char c : s) {
        if ((c & 0xC0) != 0x80) ++n;
    }
    return n;
}

inline std::string utf8Prefix(const std::string& s, int chars)
{
    int n = 0;
    size_t i = 0;
    while (i < s.size() && n < chars) {
        size_t old = i;
        nextCodepoint(s, i);
        if (i == old) break;
        ++n;
    }
    return s.substr(0, i);
}

inline std::vector<std::string> wrapText(const std::string& text, int maxChars)
{
    std::vector<std::string> lines;
    std::string line;
    int lineLen = 0;
    size_t i = 0;
    while (i <= text.size()) {
        size_t j = text.find(' ', i);
        if (j == std::string::npos) j = text.size();
        std::string word = text.substr(i, j - i);
        int wl = utf8Length(word);
        if (line.empty()) {
            line = word;
            lineLen = wl;
        } else if (lineLen + 1 + wl <= maxChars) {
            line += " ";
            line += word;
            lineLen += 1 + wl;
        } else {
            lines.push_back(line);
            line = word;
            lineLen = wl;
        }
        if (j == text.size()) break;
        i = j + 1;
    }
    if (!line.empty()) lines.push_back(line);
    return lines;
}

inline int textWidth(const std::string& s, int scale)
{
    return std::max(0, utf8Length(s) * 6 * scale - scale);
}

inline void drawTextRaw(SDL_Renderer* r, int x, int y, const std::string& text, int scale)
{
    int pen = x;
    size_t i = 0;
    while (i < text.size()) {
        uint32_t cp = normalize(nextCodepoint(text, i));
        const Glyph* g = findGlyph(cp);
        if (g) {
            for (int row = 0; row < 7; ++row) {
                const char* bits = g->rows[row];
                int c = 0;
                while (c < 5) {
                    if (bits[c] == '#') {
                        int c2 = c;
                        while (c2 < 5 && bits[c2] == '#') ++c2;
                        SDL_Rect px{pen + c * scale, y + row * scale, (c2 - c) * scale, scale};
                        SDL_RenderFillRect(r, &px);
                        c = c2;
                    } else {
                        ++c;
                    }
                }
            }
        }
        pen += 6 * scale;
    }
}

inline void drawText(SDL_Renderer* r, int x, int y, const std::string& text, int scale,
                     SDL_Color color, bool shadow = true)
{
    if (shadow) {
        SDL_SetRenderDrawColor(r, 12, 8, 12, 170);
        drawTextRaw(r, x + scale, y + scale, text, scale);
    }
    SDL_SetRenderDrawColor(r, color.r, color.g, color.b, color.a);
    drawTextRaw(r, x, y, text, scale);
}

inline void drawTextCentered(SDL_Renderer* r, int cx, int y, const std::string& text,
                             int scale, SDL_Color color, bool shadow = true)
{
    drawText(r, cx - textWidth(text, scale) / 2, y, text, scale, color, shadow);
}

